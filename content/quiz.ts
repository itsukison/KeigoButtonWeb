export const scoreBand = (correct: number) => {
  const pct = (correct / QUIZ.length) * 100;
  if (pct >= 90) return { label: "敬語マスター", note: "身内敬語や二重敬語まで判別できています。送る前の確認はほぼ不要です。" };
  if (pct >= 70) return { label: "実務レベル", note: "業務で困る場面は少ないはずです。二重敬語と身内敬語だけ注意すれば十分です。" };
  if (pct >= 50) return { label: "あと一歩", note: "尊敬語と謙譲語の切り替えで迷いが出ています。動作の主体を確認する癖をつけると安定します。" };
  return { label: "要注意", note: "意味は通じますが、目上の相手に違和感を持たれる可能性があります。送る前に一度整えることをおすすめします。" };
};
